import { spawn } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { childExitStatus } from './build-memory-policy.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const run = (command, args, env) => new Promise((resolve, reject) => {
  const child = spawn(command, args, { env, stdio: 'inherit' });
  child.once('error', reject);
  child.once('exit', (code, signal) => resolve(childExitStatus(code, signal)));
});

export async function buildNextApp({ execute = run, env = process.env, args = [] } = {}) {
  const code = await execute(process.execPath, ['--require', join(root, 'scripts/next-fs-rm-retry.cjs'),
    join(root, 'node_modules/next/dist/bin/next'), 'build', ...args],
  { ...env, ELEVATE_SEQUENTIAL_TYPECHECK: '1' });
  if (code !== 0) return code;
  // Release the compiler/module graph before type analysis allocates its heap.
  // This validates both source and the route types generated by this build.
  const checked = await execute(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'), '--noEmit'],
    { ...env, ELEVATE_SEQUENTIAL_TYPECHECK: '0' });
  if (checked === 0) console.log('[build-memory] production compilation and generated-route typecheck both passed');
  return checked;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  buildNextApp({ args: process.argv.slice(2) }).then(code => { process.exitCode = code; })
    .catch(error => { console.error(error.message); process.exitCode = 1; });
}
