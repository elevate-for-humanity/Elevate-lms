import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { syncWorkspaceRepository } from './repository-sync.mjs';
import { WorkspaceCheckpoint } from './workspace-checkpoint.mjs';
const git=(cwd,...args)=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
test('sync avoids historical media blobs and preserves tracked and untracked working files',async t=>{
 const base=await fs.mkdtemp(path.join(os.tmpdir(),'studio-sync-'));
 t.after(()=>fs.rm(base,{recursive:true,force:true}));
 const origin=path.join(base,'origin'),root=path.join(base,'workspace');await fs.mkdir(origin);
 git(origin,'init','-b','main');git(origin,'config','user.name','Fixture');git(origin,'config','user.email','fixture@example.test');git(origin,'config','uploadpack.allowFilter','true');
 await fs.writeFile(path.join(origin,'app.txt'),'first');await fs.writeFile(path.join(origin,'notes.txt'),'original');git(origin,'add','.');git(origin,'commit','-m','initial');
 const repoUrl=pathToFileURL(origin).href;
 await syncWorkspaceRepository({root,repoUrl});
 await fs.writeFile(path.join(root,'notes.txt'),'user draft');await fs.writeFile(path.join(root,'untracked.txt'),'keep me');
 await fs.writeFile(path.join(origin,'retired-video.bin'),crypto.randomBytes(8*1024*1024));git(origin,'add','.');git(origin,'commit','-m','historical media');
 git(origin,'rm','retired-video.bin');await fs.writeFile(path.join(origin,'app.txt'),'updated');git(origin,'add','.');git(origin,'commit','-m','remove historical media');
 const result=await syncWorkspaceRepository({root,repoUrl});
 assert.equal(result.sha,git(origin,'rev-parse','HEAD'));assert.equal(await fs.readFile(path.join(root,'app.txt'),'utf8'),'updated');
 assert.equal(await fs.readFile(path.join(root,'notes.txt'),'utf8'),'user draft');assert.equal(await fs.readFile(path.join(root,'untracked.txt'),'utf8'),'keep me');
 const packs=await fs.readdir(path.join(root,'.git','objects','pack'));
 let bytes=0;for(const file of packs)bytes+=(await fs.stat(path.join(root,'.git','objects','pack',file))).size;
 assert.ok(bytes<1024*1024,`historical blob downloaded: ${bytes}`);
 const checkpoint = new WorkspaceCheckpoint({root});
 const before = await checkpoint.scan();
 const repeated = await syncWorkspaceRepository({root,repoUrl});
 assert.equal(repeated.changed,false);
 assert.equal((await checkpoint.scan()).fingerprint,before.fingerprint,'unchanged reconnect must not force another full durable archive');
 assert.equal(await fs.readFile(path.join(root,'notes.txt'),'utf8'),'user draft');
 await fs.writeFile(path.join(origin,'notes.txt'),'remote change');git(origin,'add','.');git(origin,'commit','-m','conflicting change');
 await assert.rejects(syncWorkspaceRepository({root,repoUrl}));
 assert.equal(await fs.readFile(path.join(root,'notes.txt'),'utf8'),'user draft');assert.equal(await fs.readFile(path.join(root,'untracked.txt'),'utf8'),'keep me');
});
test('sync refuses a restored checkout belonging to a different requested repository',async t=>{
 const base=await fs.mkdtemp(path.join(os.tmpdir(),'studio-origin-'));t.after(()=>fs.rm(base,{recursive:true,force:true}));
 const root=path.join(base,'workspace'),origin=path.join(base,'origin');await fs.mkdir(origin);
 git(origin,'init','-b','main');git(origin,'config','user.name','Fixture');git(origin,'config','user.email','fixture@example.test');
 await fs.writeFile(path.join(origin,'app.txt'),'other project');git(origin,'add','.');git(origin,'commit','-m','initial');
 await syncWorkspaceRepository({root,repoUrl:pathToFileURL(origin).href});
 const head=git(root,'rev-parse','HEAD');
 await assert.rejects(syncWorkspaceRepository({root,repoUrl:pathToFileURL(path.join(base,'intended-repository')).href}),/repository_origin_mismatch/);
 assert.equal(git(root,'rev-parse','HEAD'),head);
 assert.equal(await fs.readFile(path.join(root,'app.txt'),'utf8'),'other project');
});
